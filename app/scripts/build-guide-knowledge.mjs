// Writes guide-api/src/knowledge.generated.ts from the portfolio's content
// modules, so the optional AI endpoint is grounded in exactly what the site says.
// Usage (from app/): node scripts/build-guide-knowledge.mjs
import { createServer } from "vite";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const vite = await createServer({
  root: app, configFile: false, logLevel: "error",
  resolve: { alias: { "~": path.join(app, "src") } },
  server: { middlewareMode: true, hmr: false }, appType: "custom", optimizeDeps: { noDiscovery: true },
});
try {
  const { buildKnowledgePack } = await vite.ssrLoadModule("/src/guide/knowledge.ts");
  const pack = buildKnowledgePack();
  const out = path.resolve(app, "../guide-api/src/knowledge.generated.ts");
  writeFileSync(out, `// GENERATED by app/scripts/build-guide-knowledge.mjs — do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(pack)};\n`);
  console.log(`wrote ${path.relative(process.cwd(), out)} (${pack.length} chars)`);
} finally {
  await vite.close();
}
